"""
GreenPath AI — PDF Report Generation Service (NEW)
Generates comprehensive downloadable environmental reports using ReportLab.
"""

import os
import uuid
import logging
from datetime import datetime
from typing import Dict, Any

logger = logging.getLogger(__name__)


def generate_environmental_report(
    analysis: Dict[str, Any],
    predictions: Dict[str, Any],
    recommendations: Dict[str, Any],
    output_dir: str,
    report_title: str = "GreenPath AI Environmental Report",
) -> str:
    """
    Generate a full PDF environmental report.

    Args:
        analysis: Full analysis result dict.
        predictions: ML predictions dict.
        recommendations: Plantation recommendations dict.
        output_dir: Directory to save the PDF.
        report_title: Title for the report.

    Returns:
        Absolute path to the generated PDF file.
    """
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import cm
        from reportlab.lib.colors import (
            HexColor, white, black, green, darkgreen
        )
        from reportlab.platypus import (
            SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle,
            HRFlowable, PageBreak, KeepTogether, Image,
        )
        from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT
    except ImportError:
        logger.error("ReportLab not installed. Cannot generate PDF.")
        raise

    os.makedirs(output_dir, exist_ok=True)
    filename = f"greenpath_report_{uuid.uuid4().hex[:8]}.pdf"
    filepath = os.path.join(output_dir, filename)

    doc = SimpleDocTemplate(
        filepath,
        pagesize=A4,
        rightMargin=2 * cm,
        leftMargin=2 * cm,
        topMargin=2 * cm,
        bottomMargin=2 * cm,
    )

    # ── Colour palette ─────────────────────────────────────────────────────
    COLOR_PRIMARY = HexColor("#10b981")    # Emerald green
    COLOR_DARK = HexColor("#064e3b")
    COLOR_ACCENT = HexColor("#f59e0b")
    COLOR_RED = HexColor("#ef4444")
    COLOR_LIGHT_BG = HexColor("#f0fdf4")
    COLOR_HEADER_BG = HexColor("#065f46")

    # ── Styles ─────────────────────────────────────────────────────────────
    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "Title",
        fontSize=22,
        fontName="Helvetica-Bold",
        textColor=white,
        alignment=TA_CENTER,
        spaceAfter=6,
    )
    subtitle_style = ParagraphStyle(
        "Subtitle",
        fontSize=11,
        fontName="Helvetica",
        textColor=HexColor("#a7f3d0"),
        alignment=TA_CENTER,
        spaceAfter=4,
    )
    section_header_style = ParagraphStyle(
        "SectionHeader",
        fontSize=13,
        fontName="Helvetica-Bold",
        textColor=COLOR_DARK,
        spaceBefore=14,
        spaceAfter=6,
        borderPad=4,
    )
    body_style = ParagraphStyle(
        "Body",
        fontSize=10,
        fontName="Helvetica",
        textColor=black,
        spaceAfter=4,
        leading=14,
    )
    metric_key_style = ParagraphStyle(
        "MetricKey",
        fontSize=9,
        fontName="Helvetica",
        textColor=HexColor("#6b7280"),
    )
    metric_val_style = ParagraphStyle(
        "MetricVal",
        fontSize=11,
        fontName="Helvetica-Bold",
        textColor=COLOR_DARK,
    )

    story = []
    ts = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")

    # ── COVER HEADER ──────────────────────────────────────────────────────
    logo_path = analysis.get("project_logo", "static/logo.png")
    if os.path.exists(logo_path):
        logo_img = Image(logo_path, width=1.3*cm, height=1.3*cm)
        header_data = [[logo_img, Paragraph(f"<b>{report_title}</b>", title_style)]]
        header_table = Table(header_data, colWidths=[1.8*cm, doc.width - 1.8*cm])
    else:
        header_data = [[Paragraph(f"<b>{report_title}</b>", title_style)]]
        header_table = Table(header_data, colWidths=[doc.width])

    header_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), COLOR_HEADER_BG),
        ("TOPPADDING", (0, 0), (-1, -1), 16),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 12),
        ("LEFTPADDING", (0, 0), (-1, -1), 12),
        ("RIGHTPADDING", (0, 0), (-1, -1), 12),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("ROUNDEDCORNERS", [10]),
    ]))
    story.append(header_table)

    gen_by = analysis.get("generated_by", "GreenPath AI Researcher")
    date_str = analysis.get("date_str", ts)
    story.append(Paragraph(
        f"<b>Generated By:</b> {gen_by} | <b>Date:</b> {date_str} | GreenPath AI Platform",
        subtitle_style,
    ))
    story.append(Spacer(1, 0.4 * cm))

    # ── SECTION 1: EXECUTIVE SUMMARY & VISUAL OVERLAY ────────────────────
    story.append(Paragraph("1. Executive Summary & Audit Images", section_header_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=COLOR_PRIMARY))
    story.append(Spacer(1, 0.2 * cm))

    tree_count = analysis.get("tree_count", 0)
    green_pct = analysis.get("green_cover_percent", 0)
    aqi = analysis.get("aqi_score", 0)
    aqi_cat = analysis.get("aqi_category", "N/A")
    eco = analysis.get("eco_index", 0)
    co2 = analysis.get("co2_absorption_kg", 0)
    heat_red = analysis.get("heat_reduction_celsius", 0)
    cooling = analysis.get("cooling_level", "N/A")
    exec_custom = analysis.get("executive_summary")

    summary_text = exec_custom or (
        f"This report presents a comprehensive AI-driven environmental analysis of the selected urban area. "
        f"A total of <b>{tree_count}</b> trees were detected using YOLOv8 deep learning. "
        f"The area has a green cover of <b>{green_pct:.1f}%</b> with an estimated AQI of "
        f"<b>{aqi} ({aqi_cat})</b>. "
        f"These {tree_count} trees collectively absorb approximately <b>{co2:.0f} kg of CO₂ per year</b>, "
        f"reducing urban temperature by <b>{heat_red:.2f}°C</b> ({cooling}). "
        f"The overall Eco-Index is <b>{eco:.0f}/100</b>."
    )
    story.append(Paragraph(summary_text, body_style))
    story.append(Spacer(1, 0.3 * cm))

    up_img_path = analysis.get("uploaded_image_path", "")
    det_img_path = analysis.get("detection_image_path", "")
    img_cells = []
    if up_img_path and os.path.exists(up_img_path):
        img_cells.append([Paragraph("<b>Uploaded Source Image</b>", body_style), Image(up_img_path, width=7.2*cm, height=5.2*cm)])
    if det_img_path and os.path.exists(det_img_path):
        img_cells.append([Paragraph("<b>YOLOv8 Detection Overlay</b>", body_style), Image(det_img_path, width=7.2*cm, height=5.2*cm)])
    if len(img_cells) == 2:
        img_table = Table([[img_cells[0][0], img_cells[1][0]], [img_cells[0][1], img_cells[1][1]]], colWidths=[doc.width*0.5, doc.width*0.5])
        img_table.setStyle(TableStyle([
            ("ALIGN", (0,0), (-1,-1), "CENTER"),
            ("VALIGN", (0,0), (-1,-1), "MIDDLE"),
            ("TOPPADDING", (0,0), (-1,-1), 4),
            ("BOTTOMPADDING", (0,0), (-1,-1), 4),
        ]))
        story.append(img_table)
        story.append(Spacer(1, 0.3 * cm))

    # ── SECTION 2: KEY METRICS TABLE ─────────────────────────────────────
    story.append(Paragraph("2. Key Environmental Metrics", section_header_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=COLOR_PRIMARY))
    story.append(Spacer(1, 0.2 * cm))

    metrics_data = [
        ["Metric", "Value", "Status"],
        ["Trees Detected", str(tree_count),
         "✅ Good" if tree_count > 20 else "⚠️ Low"],
        ["Green Cover", f"{green_pct:.2f}%",
         "✅ Good" if green_pct > 30 else "⚠️ Low"],
        ["AQI Score", str(aqi), aqi_cat],
        ["CO₂ Absorption", f"{co2:.0f} kg/year",
         "✅" if co2 > 400 else "⚠️"],
        ["Heat Reduction", f"{heat_red:.2f}°C", cooling],
        ["Eco Index", f"{eco:.0f}/100",
         "✅ Healthy" if eco > 50 else "⚠️ Needs Improvement"],
    ]

    metrics_table = Table(
        metrics_data,
        colWidths=[doc.width * 0.42, doc.width * 0.28, doc.width * 0.30],
    )
    metrics_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), COLOR_DARK),
        ("TEXTCOLOR", (0, 0), (-1, 0), white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("ALIGN", (0, 0), (-1, -1), "LEFT"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [COLOR_LIGHT_BG, white]),
        ("GRID", (0, 0), (-1, -1), 0.5, HexColor("#d1fae5")),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(metrics_table)
    story.append(Spacer(1, 0.4 * cm))

    # ── SECTION 3: TREE HEALTH SUMMARY ───────────────────────────────────
    health_summary = analysis.get("tree_health_summary", {})
    if health_summary:
        story.append(Paragraph("3. Tree Health Analysis", section_header_style))
        story.append(HRFlowable(width="100%", thickness=1.5, color=COLOR_PRIMARY))
        story.append(Spacer(1, 0.2 * cm))

        health_data = [["Health Status", "Tree Count", "Percentage"]]
        for status, count in health_summary.items():
            pct = round(count / max(tree_count, 1) * 100, 1)
            health_data.append([status.capitalize(), str(count), f"{pct}%"])

        health_table = Table(
            health_data,
            colWidths=[doc.width * 0.4, doc.width * 0.3, doc.width * 0.3],
        )
        health_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), COLOR_PRIMARY),
            ("TEXTCOLOR", (0, 0), (-1, 0), white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [COLOR_LIGHT_BG, white]),
            ("GRID", (0, 0), (-1, -1), 0.5, HexColor("#d1fae5")),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ]))
        story.append(health_table)
        story.append(Spacer(1, 0.4 * cm))

    # ── SECTION 3.5: BOTANICAL PROFILE & SPECIES CLASSIFICATION ──────────
    bot_info = analysis.get("botanical_info", {})
    sp_name = analysis.get("species_name", "Tropical Canopy Profile")
    story.append(Paragraph("3.5 Botanical Profile & Species Directory", section_header_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=COLOR_PRIMARY))
    story.append(Spacer(1, 0.2 * cm))
    bot_table_data = [
        ["Attribute", "Botanical Metadata"],
        ["Classified Species", str(sp_name)],
        ["Scientific Name", str(bot_info.get("scientific_name", "Tropical Canopy Profile"))],
        ["Family", str(bot_info.get("family", "Various Tropical Flora"))],
        ["Conservation Status", str(bot_info.get("conservation_status", "Least Concern (IUCN)"))],
        ["Native Region", str(bot_info.get("native_region", "Pantropical / Indo-Malayan"))],
        ["Ecological Uses", str(bot_info.get("uses", "High carbon sequestration, urban shade, and biodiversity support."))],
    ]
    bot_table = Table(
        bot_table_data,
        colWidths=[doc.width * 0.35, doc.width * 0.65],
    )
    bot_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), COLOR_DARK),
        ("TEXTCOLOR", (0, 0), (-1, 0), white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [COLOR_LIGHT_BG, white]),
        ("GRID", (0, 0), (-1, -1), 0.5, HexColor("#d1fae5")),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(bot_table)
    story.append(Spacer(1, 0.4 * cm))

    # ── SECTION 4: NDVI ANALYSIS ──────────────────────────────────────────
    story.append(Paragraph("4. NDVI Vegetation Analysis", section_header_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=COLOR_PRIMARY))
    story.append(Spacer(1, 0.2 * cm))

    ndvi_mean = analysis.get("ndvi_mean", 0)
    ndvi_text = (
        f"The Normalized Difference Vegetation Index (NDVI) for this area is <b>{ndvi_mean:.3f}</b>. "
        "NDVI ranges from -1 (water/bare) to +1 (dense vegetation). "
    )
    if ndvi_mean > 0.4:
        ndvi_text += "This score indicates <b>dense, healthy vegetation</b> cover."
    elif ndvi_mean > 0.2:
        ndvi_text += "This indicates <b>moderate vegetation</b> — mixed urban and green areas."
    else:
        ndvi_text += "This score suggests <b>sparse vegetation</b> with significant built-up area."

    story.append(Paragraph(ndvi_text, body_style))
    story.append(Spacer(1, 0.3 * cm))

    # ── SECTION 5: PREDICTIVE ANALYTICS ──────────────────────────────────
    if predictions:
        story.append(Paragraph("5. 12-Month Predictive Analytics", section_header_style))
        story.append(HRFlowable(width="100%", thickness=1.5, color=COLOR_PRIMARY))
        story.append(Spacer(1, 0.2 * cm))

        story.append(Paragraph(
            "Using polynomial regression models trained on environmental data, "
            "the following projections were generated for the next 12 months:",
            body_style,
        ))

        months = predictions.get("months", [])
        pred_aqi = predictions.get("predicted_aqi", [])
        pred_carbon = predictions.get("predicted_carbon_kg", [])

        if months and pred_aqi:
            pred_data = [["Month", "Predicted AQI", "Predicted CO₂ (kg)"]]
            for i, month in enumerate(months[:6]):   # show 6 months
                pred_data.append([
                    month,
                    str(round(pred_aqi[i], 1)) if i < len(pred_aqi) else "—",
                    str(round(pred_carbon[i], 0)) if i < len(pred_carbon) else "—",
                ])

            pred_table = Table(
                pred_data,
                colWidths=[doc.width * 0.33, doc.width * 0.33, doc.width * 0.34],
            )
            pred_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), COLOR_ACCENT),
                ("TEXTCOLOR", (0, 0), (-1, 0), white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [HexColor("#fffbeb"), white]),
                ("GRID", (0, 0), (-1, -1), 0.5, HexColor("#fde68a")),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ]))
            story.append(pred_table)
            story.append(Spacer(1, 0.2 * cm))

        # Add insights
        for insight in predictions.get("insights", [])[:3]:
            story.append(Paragraph(f"• {insight}", body_style))
        story.append(Spacer(1, 0.3 * cm))

    # ── SECTION 6: RECOMMENDATIONS ────────────────────────────────────────
    if recommendations:
        story.append(Paragraph("6. AI Plantation Recommendations", section_header_style))
        story.append(HRFlowable(width="100%", thickness=1.5, color=COLOR_PRIMARY))
        story.append(Spacer(1, 0.2 * cm))

        urgency = recommendations.get("urgency", "Moderate")
        trees_needed = recommendations.get("trees_needed", 0)
        priority_zones = recommendations.get("priority_zones", [])

        story.append(Paragraph(
            f"<b>Urgency Level:</b> {urgency} | "
            f"<b>Trees Recommended:</b> {trees_needed} | "
            f"<b>Priority Zones:</b> {', '.join(priority_zones)}",
            body_style,
        ))
        story.append(Spacer(1, 0.15 * cm))

        # Species table
        species_list = recommendations.get("recommended_species", [])
        if species_list:
            species_data = [["Tree Species", "CO₂/Year", "Heat Reduction", "Growth"]]
            for sp in species_list[:3]:
                species_data.append([
                    sp.get("name", ""),
                    f"{sp.get('co2_absorption_kg_year', 0)} kg",
                    sp.get("heat_reduction", ""),
                    sp.get("growth_speed", ""),
                ])

            sp_table = Table(
                species_data,
                colWidths=[
                    doc.width * 0.40, doc.width * 0.20,
                    doc.width * 0.22, doc.width * 0.18
                ],
            )
            sp_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), COLOR_DARK),
                ("TEXTCOLOR", (0, 0), (-1, 0), white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [COLOR_LIGHT_BG, white]),
                ("GRID", (0, 0), (-1, -1), 0.5, HexColor("#d1fae5")),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ]))
            story.append(sp_table)
            story.append(Spacer(1, 0.2 * cm))

        # Action plan
        story.append(Paragraph("<b>Action Plan:</b>", body_style))
        for step in recommendations.get("action_plan", []):
            story.append(Paragraph(step, body_style))
        story.append(Spacer(1, 0.3 * cm))

